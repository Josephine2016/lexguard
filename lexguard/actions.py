"""Action layer: turns a classified case into artefacts — institution routing,
draft complaint letters, and a persistent case record (DynamoDB in prod).
"""
import json, time, uuid
from .categories import CATEGORIES

COMPLAINT_TEMPLATES = {
  "National Human Rights Commission":
    "PETITION TO THE NATIONAL HUMAN RIGHTS COMMISSION\n\nTo the Executive Secretary, NHRC,\n\nComplainant: {name}\nDate of incident: {date}\n\nFACTS:\n{facts}\n\nRIGHTS ENGAGED:\n{grounds}\n\nRELIEF SOUGHT:\nInvestigation of the above violation and appropriate redress in accordance with the NHRC Act and the Constitution.\n\nAnnexed: supporting evidence (list).",
  "Nigeria Data Protection Commission (NDPC)":
    "COMPLAINT TO THE NIGERIA DATA PROTECTION COMMISSION\n\nTo the National Commissioner, NDPC,\n\nData Subject: {name}\nData Controller/Processor concerned: {subject}\n\nDESCRIPTION OF VIOLATION:\n{facts}\n\nRIGHTS ENGAGED (NDPA 2023):\n{grounds}\n\nRELIEF SOUGHT:\nInvestigation, enforcement notice, and order for cessation/deletion of unlawfully processed personal data, pursuant to the NDPA 2023 (including s.40 complaint mechanism).",
  "Police Service Commission (Complaints)":
    "COMPLAINT AGAINST POLICE OFFICER(S)\n\nTo the Chairman, Police Service Commission,\n\nComplainant: {name}\nOfficers involved: {subject}\nDate/Place: {date}\n\nFACTS:\n{facts}\n\nLAWS ENGAGED:\n{grounds}\n\nRELIEF SOUGHT:\nDisciplinary action against the officers and compensation pursuant to the Constitution (s.34, s.35) and the Police Act 2020.",
  "DEFAULT":
    "COMPLAINT / REQUEST FOR ASSISTANCE\n\nTo: {institution}\n\nFrom: {name}\nDate of incident: {date}\n\nFACTS:\n{facts}\n\nLEGAL GROUNDING:\n{grounds}\n\nRELIEF SOUGHT:\nInvestigation and appropriate remedy.\n\n(Auto-generated by LexGuard; to be reviewed by a human before submission.)",
}

def route(category):
    return CATEGORIES.get(category, {}).get("institutions", ["National Human Rights Commission"])

def draft_complaint(institution, case):
    tpl = COMPLAINT_TEMPLATES.get(institution, COMPLAINT_TEMPLATES["DEFAULT"])
    grounds = "\n".join(f"- {d['title']}" for _, d in case["grounds"][:3])
    return tpl.format(institution=institution, name=case.get("name", "[name]"),
                      date=case.get("date", "[date]"), subject=case.get("subject", "[parties involved]"),
                      facts=case["message"], grounds=grounds)

def save_case(case, path):
    case = dict(case)
    case["case_id"] = uuid.uuid4().hex[:10]
    case["created_at"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    with open(path, "a") as f:
        f.write(json.dumps(case, ensure_ascii=False) + "\n")
    return case["case_id"]
